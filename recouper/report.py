"""Static HTML report.

Deliberately a generated file rather than a served dashboard. A report that
is a single self-contained HTML file opens instantly, has no ports, no
startup race and no blank-page-while-booting failure mode -- which matters
when it is being shown live in a recorded demo. It also means a reviewer can
open the result without running our code.

No external assets: the CSS is inline and there are no scripts, so it renders
identically offline and cannot break because a CDN moved.
"""

